/* 16×16 pixel-art sprites + SVG renderer.
   Sprite format: 16-line string, '.'=transparent, '#'=fg, '@'=accent, 'x'=muted. */

import type { CSSProperties, ReactElement } from "react";

type Palette = Record<string, string>;

const DOT_PAL: Palette = {
  "#": "var(--fg)",
  "@": "var(--accent)",
  x: "var(--muted)",
};

export function DotSprite({
  sheet,
  scale = 8,
  palette = DOT_PAL,
  style,
}: {
  sheet: string;
  scale?: number;
  palette?: Palette;
  style?: CSSProperties;
}) {
  const rows = sheet.replace(/^\n+|\n+$/g, "").split("\n");
  const h = rows.length;
  const w = Math.max(...rows.map((r) => r.length));
  const cells: ReactElement[] = [];
  for (let y = 0; y < h; y++) {
    const row = rows[y];
    for (let x = 0; x < w; x++) {
      const ch = row[x] || ".";
      const fill = palette[ch];
      if (!fill) continue;
      cells.push(<rect key={`${x},${y}`} x={x} y={y} width="1" height="1" fill={fill} />);
    }
  }
  return (
    <svg
      className="pixel"
      width={w * scale}
      height={h * scale}
      viewBox={`0 0 ${w} ${h}`}
      style={{ display: "block", ...style }}
      shapeRendering="crispEdges"
    >
      {cells}
    </svg>
  );
}

