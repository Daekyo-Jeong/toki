export const STAGE_BASE: Record<string, string> = {
  egg: D_EGG,
  baby: D_BABY,
  teen: D_TEEN,
  adult: D_ADULT,
  elder: D_ELDER,
};

/** Pick the sprite for a given stage + mode. Baby has full variants; others fall back to base. */
export function spriteFor(stage: string, mode: Mode): string {
  if (stage === "baby") {
    switch (mode) {
      case "eating": return D_BABY_EAT;
      case "sulk": return D_BABY_SULK;
      case "sleep": return D_BABY_SLEEP;
      case "blink": return D_BABY_BLINK;
      default: return D_BABY;
    }
  }
  return STAGE_BASE[stage] ?? D_EGG;
}

export type Mode = "alive" | "eating" | "sulk" | "sleep" | "blink";

